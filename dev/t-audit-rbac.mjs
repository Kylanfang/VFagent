import { api, login, check, group, summary, uid } from "./testlib.mjs";

const tag = uid();
const boss = await login("central", (process.env.VF_BOSS_P ?? "vfletch-dev"));
const T = boss.token;
let r;

group("审计分权：本人/本部门直接改，其余需主控审批");
r = await api("POST", "/api/admin/users", { token: T, body: { username: `fin_${tag}`, password: "fin123456", display_name: "财务甲", role: "employee" } });
const empUser = r.data;
const emp = await login(`fin_${tag}`, "fin123456");
r = await api("PUT", "/api/audit/record", { token: emp.token, body: { key: "employees", action: "update", index: 0, patch: { position: "x" } } });
check("未分配部门且非本人 → 进入审批", r.status === 200 && r.data.pending === true, JSON.stringify(r.data));
r = await api("POST", `/api/admin/users/${empUser.id}/department`, { token: T, body: { department: "财务部" } });
check("主控设置成员部门", r.status === 200 && r.data.department === "财务部", JSON.stringify(r.data));
r = await api("GET", "/api/auth/me", { token: emp.token });
check("me 返回部门", r.data.user?.department === "财务部");
const audit = (await api("GET", "/api/audit/overview", { token: emp.token })).data;
const empIdx = (audit.employees ?? []).findIndex((e) => e.department === "财务部");
const otherIdx = (audit.employees ?? []).findIndex((e) => e.department && e.department !== "财务部");
check("演示数据里有本部门与他部门记录", empIdx >= 0 && otherIdx >= 0, `${empIdx},${otherIdx}`);
const origPos = audit.employees[empIdx].position;
const origOther = audit.employees[otherIdx].position;
r = await api("PUT", "/api/audit/record", { token: emp.token, body: { key: "employees", action: "update", index: empIdx, patch: { position: origPos + "·改" } } });
check("成员改本部门记录 → 直接生效", r.status === 200 && r.data.applied === true, JSON.stringify(r.data));
r = await api("PUT", "/api/audit/record", { token: emp.token, body: { key: "employees", action: "update", index: otherIdx, patch: { position: "越权改" } } });
check("成员改他部门记录 → 进入审批", r.status === 200 && r.data.pending === true, JSON.stringify(r.data));
r = await api("PUT", "/api/audit/record", { token: emp.token, body: { key: "dashboardStats", action: "update", patch: { totalRisks: 1 } } });
check("成员改全局指标 → 进入审批", r.status === 200 && r.data.pending === true);
r = await api("PUT", "/api/audit/record", { token: emp.token, body: { key: "employees", action: "add", record: { id: `EMP-T${tag}`, name: "新人", department: "财务部", position: "出纳" } } });
check("成员新增本部门记录 → 直接生效", r.status === 200 && r.data.applied === true, JSON.stringify(r.data));
r = await api("GET", "/api/audit/edits/mine", { token: emp.token });
check("成员看到自己的待审申请 ≥ 3", r.status === 200 && r.data.requests.filter((q) => q.status === "pending").length >= 3, JSON.stringify(r.data).slice(0, 200));
r = await api("GET", "/api/audit/edits", { token: emp.token });
check("成员不能看审批队列 403", r.status === 403);
r = await api("GET", "/api/audit/edits", { token: T });
check("主控看到待审批且已解析 key/reason", r.status === 200 && r.data.requests.some((q) => q.key === "employees" && q.reason), JSON.stringify(r.data).slice(0, 200));
const reqEmp = r.data.requests.find((q) => q.key === "employees" && q.requestedBy === `fin_${tag}` && q.index === otherIdx);
const reqStats = r.data.requests.find((q) => q.key === "dashboardStats" && q.requestedBy === `fin_${tag}`);
r = await api("POST", "/api/audit/edits/apply", { token: T, body: { id: reqEmp.id } });
check("主控批准他部门修改", r.status === 200, JSON.stringify(r.data));
r = await api("POST", "/api/audit/edits/reject", { token: T, body: { id: reqStats.id } });
check("主控驳回全局指标修改", r.status === 200);
const after = (await api("GET", "/api/audit/overview", { token: T })).data;
check("批准后记录已应用", after.employees[otherIdx].position === "越权改", after.employees[otherIdx].position);
check("驳回后全局指标未变", after.dashboardStats.totalRisks !== 1);
r = await api("GET", "/api/audit/edits/mine", { token: emp.token });
check("成员看到申请状态 已批准/已驳回", r.data.requests.some((q) => q.status === "applied") && r.data.requests.some((q) => q.status === "rejected"));
r = await api("POST", "/api/audit/edits/apply", { token: T, body: { id: reqEmp.id } });
check("重复批准 404", r.status === 404);

group("还原与清理");
r = await api("PUT", "/api/audit/record", { token: T, body: { key: "employees", action: "update", index: empIdx, patch: { position: origPos } } });
r = await api("PUT", "/api/audit/record", { token: T, body: { key: "employees", action: "update", index: otherIdx, patch: { position: origOther } } });
const addedIdx = after.employees.findIndex((e) => e.id === `EMP-T${tag}`);
if (addedIdx >= 0) r = await api("PUT", "/api/audit/record", { token: T, body: { key: "employees", action: "delete", index: addedIdx } });
check("删除测试新增记录", r.status === 200);
// 驳回其余挂起申请，保持队列干净
r = await api("GET", "/api/audit/edits", { token: T });
for (const q of r.data.requests.filter((x) => x.requestedBy === `fin_${tag}`)) await api("POST", "/api/audit/edits/reject", { token: T, body: { id: q.id } });
r = await api("DELETE", `/api/admin/users/${empUser.id}`, { token: T });
check("删除测试成员", r.status === 200);
process.exit(summary() ? 0 : 1);
